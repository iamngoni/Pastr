import AppKit
import ImageIO

final class ClipboardMonitor {
    private let historyStore: ClipboardHistoryStore
    private let settingsStore = SettingsStore.shared
    private let pasteQueue = PasteQueue.shared
    private let pasteboard = NSPasteboard.general
    private var changeCount: Int?
    private var timer: DispatchSourceTimer?
    private let monitorQueue = DispatchQueue(label: "com.pastr.clipboard-monitor", qos: .userInitiated)

    // Pasteboard types that indicate confidential content
    private static let confidentialTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    // Pasteboard types that indicate transient content
    private static let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")
    ]

    private static let imageTypes: Set<NSPasteboard.PasteboardType> = [.tiff, .png, .pdf]
    private static let explicitStoredTypes: Set<NSPasteboard.PasteboardType> = [.string, .rtf, .URL, .tiff, .png, .pdf]
    private static let maxStoredRepresentationBytes = 2 * 1024 * 1024
    private static let maxStoredRepresentationsTotalBytes = 8 * 1024 * 1024
    private static let maxCapturedImageBytes = 25 * 1024 * 1024
    private static let maxNormalizedImageBytes = 8 * 1024 * 1024
    private static let maxImagePixelDimension = 2_048

    init(historyStore: ClipboardHistoryStore) {
        self.historyStore = historyStore
    }

    deinit {
        stop()
    }

    func start() {
        stop()
        let timer = DispatchSource.makeTimerSource(queue: monitorQueue)
        timer.schedule(deadline: .now(), repeating: .milliseconds(450))
        timer.setEventHandler { [weak self] in
            self?.pollPasteboard()
        }
        timer.resume()
        self.timer = timer
    }

    func stop() {
        timer?.cancel()
        timer = nil
    }

    private func pollPasteboard() {
        let currentChangeCount = pasteboard.changeCount
        guard let previousChangeCount = changeCount else {
            // Establish the baseline on the monitor queue. Reading NSPasteboard during app
            // construction can synchronously wait on pboard/XPC and stall launch.
            changeCount = currentChangeCount
            return
        }
        guard currentChangeCount != previousChangeCount else { return }
        changeCount = currentChangeCount
        autoreleasepool {
            capturePasteboardItem()
        }
    }

    private func capturePasteboardItem() {
        guard let pasteboardItem = pasteboard.pasteboardItems?.first else { return }

        let types = pasteboardItem.types

        // Check for confidential content (passwords, etc.)
        if settingsStore.ignoreConfidentialContent {
            for confType in ClipboardMonitor.confidentialTypes {
                if types.contains(confType) {
                    return // Skip confidential content
                }
            }
        }

        // Check for transient content (auto-generated, temporary)
        if settingsStore.ignoreTransientContent {
            for transType in ClipboardMonitor.transientTypes {
                if types.contains(transType) {
                    return // Skip transient content
                }
            }
        }

        // Check if this is a Universal Clipboard item from another device
        let isUniversalClipboard = isFromUniversalClipboard(pasteboardItem)

        var bundleId: String?
        var appName: String?

        if isUniversalClipboard {
            // Don't attribute to frontmost app if it came from another device
            bundleId = nil
            // Try to extract device name, fallback to generic label
            if let deviceName = extractUniversalClipboardDeviceName(pasteboardItem) {
                appName = deviceName
            } else {
                appName = "Another Device"
            }
        } else {
            let frontmost = NSWorkspace.shared.frontmostApplication
            bundleId = frontmost?.bundleIdentifier
            appName = frontmost?.localizedName
        }

        // Skip if from Pastr itself
        if bundleId == Bundle.main.bundleIdentifier {
            return
        }

        // Check if the source app is in the ignored list
        if settingsStore.isAppIgnored(bundleId) {
            return // Skip content from ignored apps
        }

        let item = ClipboardMonitor.makeClipboardItem(
            from: pasteboardItem,
            pasteboard: pasteboard,
            sourceBundleId: bundleId,
            sourceName: appName
        )

        DispatchQueue.main.async { [weak self] in
            guard let self else { return }
            // Add to history
            self.historyStore.add(item)
            // Also add to paste queue if queue mode is active
            if self.pasteQueue.isActive {
                self.pasteQueue.enqueue(item)
            }
        }
    }

    private func isFromUniversalClipboard(_ item: NSPasteboardItem) -> Bool {
        // Check for Apple's Universal Clipboard marker types
        let types = item.types

        // Universal Clipboard items often have these markers
        let universalClipboardMarkers: [NSPasteboard.PasteboardType] = [
            NSPasteboard.PasteboardType("com.apple.is-remote-clipboard"),
            NSPasteboard.PasteboardType("com.apple.CloudDocs.UTI")
        ]

        for marker in universalClipboardMarkers {
            if types.contains(marker) {
                return true
            }
        }

        return false
    }

    /// Attempts to extract the source device name from Universal Clipboard metadata
    private func extractUniversalClipboardDeviceName(_ item: NSPasteboardItem) -> String? {
        // Debug: Log all pasteboard types for Universal Clipboard items
        #if DEBUG
        print("[Pastr] Universal Clipboard detected. Available types:")
        for type in item.types {
            print("  - \(type.rawValue)")
            if let data = item.data(forType: type) {
                print("    Data size: \(data.count) bytes")
                if data.count < 500, let str = String(data: data, encoding: .utf8) {
                    print("    As UTF8: \(str.prefix(200))")
                }
            }
        }
        #endif

        // Try known Apple pasteboard types that might contain device info
        let potentialTypes: [NSPasteboard.PasteboardType] = [
            NSPasteboard.PasteboardType("com.apple.is-remote-clipboard"),
            NSPasteboard.PasteboardType("com.apple.pasteboard.source-device"),
            NSPasteboard.PasteboardType("com.apple.UIKit.origin-device"),
            NSPasteboard.PasteboardType("com.apple.pasteboard.sender-device-name"),
            NSPasteboard.PasteboardType("com.apple.pasteboard.owner")
        ]

        for type in potentialTypes {
            if let data = item.data(forType: type) {
                // Try to decode as UTF-8 string
                if let string = String(data: data, encoding: .utf8), !string.isEmpty {
                    // Filter out non-printable characters and check if it looks like a device name
                    let cleaned = string.trimmingCharacters(in: .controlCharacters)
                    if !cleaned.isEmpty && cleaned.count < 100 {
                        return cleaned
                    }
                }

                // Try to decode as property list (plist)
                if let plist = try? PropertyListSerialization.propertyList(from: data, options: [], format: nil) {
                    if let dict = plist as? [String: Any] {
                        // Look for common keys that might contain device name
                        let deviceNameKeys = ["deviceName", "device-name", "DeviceName", "senderDeviceName", "sourceName", "name"]
                        for key in deviceNameKeys {
                            if let name = dict[key] as? String {
                                return name
                            }
                        }
                    } else if let name = plist as? String {
                        return name
                    }
                }
            }
        }

        // Also check if there's a source app bundle ID from another device
        if let sourceApp = item.string(forType: NSPasteboard.PasteboardType("com.apple.pasteboard.source-app")) {
            // Extract app name from bundle ID if available
            if sourceApp.contains(".") {
                let components = sourceApp.split(separator: ".")
                if let lastComponent = components.last {
                    return String(lastComponent)
                }
            }
            return sourceApp
        }

        return nil
    }

    private static func makeClipboardItem(
        from item: NSPasteboardItem,
        pasteboard: NSPasteboard,
        sourceBundleId: String?,
        sourceName: String?
    ) -> ClipboardItem {
        let textContent = item.string(forType: .string)
        let rtfData = item.data(forType: .rtf)

        let imageData = ClipboardMonitor.imageData(from: item, pasteboard: pasteboard)

        let urlString = item.string(forType: .URL)

        let fileURLs = (pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        let typesData = ClipboardMonitor.storedRepresentations(from: item, hasExplicitImageData: imageData != nil)

        let type = ClipboardMonitor.resolveType(
            text: textContent,
            rtf: rtfData,
            imageData: imageData,
            urlString: urlString,
            fileURLs: fileURLs
        )

        let fingerprint = ClipboardMonitor.fingerprint(
            for: typesData,
            text: textContent,
            rtfData: rtfData,
            imageData: imageData,
            url: urlString,
            files: fileURLs
        )

        return ClipboardItem(
            id: UUID(),
            createdAt: Date(),
            type: type,
            textContent: textContent,
            rtfData: rtfData,
            imageData: imageData,
            urlString: urlString,
            fileURLs: fileURLs,
            sourceAppBundleId: sourceBundleId,
            sourceAppName: sourceName,
            isPinned: false,
            pinnedTitle: nil,
            typesData: typesData,
            fingerprint: fingerprint
        )
    }

    private static func storedRepresentations(
        from item: NSPasteboardItem,
        hasExplicitImageData: Bool
    ) -> [NSPasteboard.PasteboardType: Data] {
        var typesData: [NSPasteboard.PasteboardType: Data] = [:]
        var totalBytes = 0

        for type in item.types where shouldStoreRepresentation(type, hasExplicitImageData: hasExplicitImageData) {
            let data = item.data(forType: type) ?? item.string(forType: type)?.data(using: .utf8)
            guard let data,
                  data.count <= maxStoredRepresentationBytes,
                  totalBytes + data.count <= maxStoredRepresentationsTotalBytes else {
                continue
            }
            typesData[type] = data
            totalBytes += data.count
        }

        return typesData
    }

    private static func shouldStoreRepresentation(
        _ type: NSPasteboard.PasteboardType,
        hasExplicitImageData: Bool
    ) -> Bool {
        if explicitStoredTypes.contains(type) {
            return false
        }
        if hasExplicitImageData, imageTypes.contains(type) {
            return false
        }
        return true
    }

    private static func imageData(from item: NSPasteboardItem, pasteboard: NSPasteboard) -> Data? {
        if let pngData = item.data(forType: .png), pngData.count <= maxCapturedImageBytes {
            return pngData
        }
        if let tiffData = item.data(forType: .tiff),
           let pngData = normalizedPNGData(from: tiffData) {
            return pngData
        }
        if let pdfData = item.data(forType: .pdf) {
            if pdfData.count <= maxCapturedImageBytes {
                return pdfData
            }
            if let pngData = normalizedPNGData(from: pdfData) {
                return pngData
            }
        }
        if pasteboard.canReadObject(forClasses: [NSImage.self], options: nil),
           let images = pasteboard.readObjects(forClasses: [NSImage.self], options: nil) as? [NSImage],
           let image = images.first {
            return normalizedPNGData(from: image)
        }
        return nil
    }

    private static func normalizedPNGData(from data: Data) -> Data? {
        guard data.count <= maxCapturedImageBytes,
              let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceShouldCache: false,
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxImagePixelDimension
        ]
        guard let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else {
            return nil
        }
        return pngData(from: cgImage)
    }

    private static func normalizedPNGData(from image: NSImage) -> Data? {
        var rect = CGRect(origin: .zero, size: image.size)
        guard let cgImage = image.cgImage(forProposedRect: &rect, context: nil, hints: nil) else {
            return nil
        }
        return pngData(from: cgImage)
    }

    private static func pngData(from cgImage: CGImage) -> Data? {
        let bitmap = NSBitmapImageRep(cgImage: cgImage)
        guard let data = bitmap.representation(using: .png, properties: [:]),
              data.count <= maxNormalizedImageBytes else { return nil }
        return data
    }

    private static func resolveType(
        text: String?,
        rtf: Data?,
        imageData: Data?,
        urlString: String?,
        fileURLs: [URL]
    ) -> ClipboardItemType {
        if imageData != nil {
            return .image
        }
        if let urlString, !urlString.isEmpty {
            return .link
        }
        if !fileURLs.isEmpty {
            return .file
        }
        if rtf != nil {
            return .richText
        }
        if let text, !text.isEmpty {
            return .text
        }
        return .other
    }

    private static func fingerprint(
        for typesData: [NSPasteboard.PasteboardType: Data],
        text: String?,
        rtfData: Data?,
        imageData: Data?,
        url: String?,
        files: [URL]
    ) -> String {
        var hasher = Hasher()
        hasher.combine(text)
        hasher.combine(rtfData)
        hasher.combine(imageData)
        hasher.combine(url)
        hasher.combine(files.map { $0.absoluteString }.joined(separator: ","))
        for type in typesData.keys.sorted(by: { $0.rawValue < $1.rawValue }) {
            hasher.combine(type.rawValue)
            hasher.combine(typesData[type])
        }
        return String(hasher.finalize())
    }
}
