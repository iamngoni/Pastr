import Foundation

/// On-device AI enrichment data for a single clipboard item, keyed by `fingerprint`.
///
/// All fields are produced locally (Vision / NaturalLanguage / Apple Intelligence) and
/// never leave the device. Each field is optional and filled in progressively as the
/// relevant enrichment pass completes, so a record may be partially populated.
struct AIEnrichment: Codable, Hashable {
    /// The clip this enrichment belongs to.
    let fingerprint: String

    /// Text recognised from an image clip via Vision OCR.
    var ocrText: String?

    /// Sentence embedding used for semantic search (NaturalLanguage). Stored as `Float`
    /// for compactness; compared with cosine similarity.
    var embedding: [Float]?

    /// Coarse content category inferred on-device (see `ContentCategory`).
    var category: ContentCategory?

    /// Tag names suggested by the classifier. These are *suggestions* — they are not
    /// applied automatically unless auto-tagging is enabled.
    var tagSuggestions: [String]

    /// How sensitive the clip looks (secrets, cards, etc.).
    var sensitivity: SensitivityLevel

    /// One-line title generated by Apple Intelligence (Tier 2).
    var generatedTitle: String?

    /// Short summary generated by Apple Intelligence (Tier 2).
    var summary: String?

    /// Schema/content version used to decide whether a clip needs re-enrichment when the
    /// pipeline changes.
    var pipelineVersion: Int

    init(
        fingerprint: String,
        ocrText: String? = nil,
        embedding: [Float]? = nil,
        category: ContentCategory? = nil,
        tagSuggestions: [String] = [],
        sensitivity: SensitivityLevel = .none,
        generatedTitle: String? = nil,
        summary: String? = nil,
        pipelineVersion: Int = AIEnrichment.currentPipelineVersion
    ) {
        self.fingerprint = fingerprint
        self.ocrText = ocrText
        self.embedding = embedding
        self.category = category
        self.tagSuggestions = tagSuggestions
        self.sensitivity = sensitivity
        self.generatedTitle = generatedTitle
        self.summary = summary
        self.pipelineVersion = pipelineVersion
    }

    /// Bump when the deterministic (Tier 1) pipeline changes in a way that invalidates
    /// previously computed enrichment. Tier 2 (LLM) fields are generated on demand and are
    /// not gated by this.
    static let currentPipelineVersion = 1

    /// True when the deterministic enrichment is stale relative to the current pipeline.
    var needsReprocessing: Bool {
        pipelineVersion < AIEnrichment.currentPipelineVersion
    }

    /// All searchable text contributed by enrichment (currently OCR text).
    var searchableText: String? {
        guard let ocrText, !ocrText.isEmpty else { return nil }
        return ocrText
    }
}

/// Coarse, on-device content classification used for smart filtering and tag suggestions.
enum ContentCategory: String, Codable, CaseIterable, Hashable {
    case code
    case url
    case email
    case phone
    case address
    case number
    case color
    case json
    case command
    case prose
    case other

    var label: String {
        switch self {
        case .code: return "Code"
        case .url: return "Link"
        case .email: return "Email"
        case .phone: return "Phone"
        case .address: return "Address"
        case .number: return "Number"
        case .color: return "Color"
        case .json: return "JSON"
        case .command: return "Command"
        case .prose: return "Text"
        case .other: return "Other"
        }
    }

    var systemImage: String {
        switch self {
        case .code: return "chevron.left.forwardslash.chevron.right"
        case .url: return "link"
        case .email: return "envelope"
        case .phone: return "phone"
        case .address: return "mappin.and.ellipse"
        case .number: return "number"
        case .color: return "paintpalette"
        case .json: return "curlybraces"
        case .command: return "terminal"
        case .prose: return "text.alignleft"
        case .other: return "doc"
        }
    }
}

/// How sensitive a clip appears, based on local pattern detection. Drives optional UI
/// blurring and exclusion from sync/backup.
enum SensitivityLevel: String, Codable, Hashable, Comparable {
    /// Nothing sensitive detected.
    case none
    /// Looks like personal data (email, phone) worth a soft warning.
    case low
    /// Looks like a secret (API key, password, card number, private key).
    case high

    private var rank: Int {
        switch self {
        case .none: return 0
        case .low: return 1
        case .high: return 2
        }
    }

    static func < (lhs: SensitivityLevel, rhs: SensitivityLevel) -> Bool {
        lhs.rank < rhs.rank
    }

    var isSensitive: Bool { self != .none }

    var label: String {
        switch self {
        case .none: return "Not sensitive"
        case .low: return "Possibly personal"
        case .high: return "Possible secret"
        }
    }
}
