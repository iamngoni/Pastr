    private func startBackup() {
        let panel = NSSavePanel()
        panel.allowedContentTypes = [UTType(exportedAs: "dev.iamngoni.pastr.backup")]
        panel.canCreateDirectories = true
        panel.nameFieldStringValue =
            "Pastr Backup \(DateFormatter.backupNameFormatter.string(from: Date())).pastrbackup"
        presentSavePanel(panel) { url in
            guard let url else { return }
            if settings.encryptBackups {
                pendingBackupURL = url
                passwordPromptMode = .backup
                showPasswordPrompt = true
            } else {
                performBackup(to: url, password: nil)
            }
        }
    }

    private func startRestore() {
        let panel = NSOpenPanel()
        panel.allowedContentTypes = [UTType(exportedAs: "dev.iamngoni.pastr.backup"), .json]
        panel.canChooseFiles = true
        panel.canChooseDirectories = false
        presentOpenPanel(panel) { url in
            guard let url else { return }
            do {
                let data = try Data(contentsOf: url)
                if backupManager.isEncryptedBackup(data) {
                    pendingRestoreURL = url
                    passwordPromptMode = .restore
                    showPasswordPrompt = true
                } else {
                    performRestore(from: url, password: nil)
                }
            } catch {
                backupAlertMessage = "Could not read backup: \(error.localizedDescription)"
            }
        }
    }

    private func export(format: ExportFormat) {
        let panel = NSSavePanel()
        panel.canCreateDirectories = true
        switch format {
        case .json:
            panel.allowedContentTypes = [.json]
            panel.nameFieldStringValue =
                "Pastr Export \(DateFormatter.backupNameFormatter.string(from: Date())).json"
        case .csv:
            panel.allowedContentTypes = [.commaSeparatedText]
            panel.nameFieldStringValue =
                "Pastr Export \(DateFormatter.backupNameFormatter.string(from: Date())).csv"
        }
        presentSavePanel(panel) { url in
            guard let url else { return }
            runBackupTask(message: "Exporting...") {
                try backupManager.export(items: historyStore.items, to: url, format: format)
                return "Export saved."
            }
        }
    }

    private func performBackup(to url: URL, password: String?) {
        runBackupTask(message: "Creating backup...") {
            try backupManager.createBackup(items: historyStore.items, to: url, password: password)
            return "Backup saved."
        }
        clearPendingBackup()
    }

    private func performRestore(from url: URL, password: String?) {
        runBackupTask(message: "Restoring backup...") {
            let items = try backupManager.restoreBackup(from: url, password: password)
            DispatchQueue.main.async {
                historyStore.replaceAll(with: items)
            }
            return "Backup restored."
        }
        clearPendingBackup()
    }

    private func handlePasswordConfirm(_ password: String) {
        showPasswordPrompt = false
        if let url = pendingBackupURL {
            performBackup(to: url, password: password)
            return
        }
        if let url = pendingRestoreURL {
            performRestore(from: url, password: password)
            return
        }
        clearPendingBackup()
    }

    private func clearPendingBackup() {
        pendingBackupURL = nil
        pendingRestoreURL = nil
        showPasswordPrompt = false
    }

    private func runBackupTask(message: String, task: @escaping () throws -> String) {
        backupWorkingMessage = message
        isBackupWorking = true
        DispatchQueue.global(qos: .userInitiated).async {
            do {
                let successMessage = try task()
                DispatchQueue.main.async {
                    isBackupWorking = false
                    backupAlertMessage = successMessage
                }
            } catch {
                DispatchQueue.main.async {
                    isBackupWorking = false
                    backupAlertMessage = "Operation failed: \(error.localizedDescription)"
                }
            }
        }
    }

    private func presentSavePanel(_ panel: NSSavePanel, completion: @escaping (URL?) -> Void) {
        NSApp.activate(ignoringOtherApps: true)
        if let window = NSApp.keyWindow ?? NSApp.windows.first {
            panel.beginSheetModal(for: window) { response in
                completion(response == .OK ? panel.url : nil)
            }
        } else {
            let response = panel.runModal()
            completion(response == .OK ? panel.url : nil)
        }
    }

    private func presentOpenPanel(_ panel: NSOpenPanel, completion: @escaping (URL?) -> Void) {
        NSApp.activate(ignoringOtherApps: true)
        if let window = NSApp.keyWindow ?? NSApp.windows.first {
            panel.beginSheetModal(for: window) { response in
                completion(response == .OK ? panel.url : nil)
            }
        } else {
            let response = panel.runModal()
            completion(response == .OK ? panel.url : nil)
        }
    }
}

private enum PasswordPromptMode {
    case backup
    case restore

    var title: String {
        switch self {
        case .backup:
            return "Encrypt Backup"
        case .restore:
            return "Decrypt Backup"
        }
    }

    var requiresConfirmation: Bool {
        switch self {
        case .backup: return true
        case .restore: return false
        }
    }
}

private struct BackupPasswordPrompt: View {
    let mode: PasswordPromptMode
    let onCancel: () -> Void
    let onConfirm: (String) -> Void

    @State private var password = ""
    @State private var confirmPassword = ""
    @State private var errorMessage: String?

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            Text(mode.title)
                .font(.system(size: 16, weight: .semibold))

            SecureField("Password", text: $password)
                .textFieldStyle(.roundedBorder)

            if mode.requiresConfirmation {
                SecureField("Confirm Password", text: $confirmPassword)
                    .textFieldStyle(.roundedBorder)
            }

            if let errorMessage {
                Text(errorMessage)
                    .font(.system(size: 11))
                    .foregroundColor(Color(red: 0.98, green: 0.45, blue: 0.4))
            }

            HStack {
                Button("Cancel") {
                    onCancel()
                }
                Spacer()
                Button(mode == .backup ? "Encrypt" : "Unlock") {
                    guard !password.isEmpty else {
                        errorMessage = "Password is required."
                        return
                    }
                    if mode.requiresConfirmation, password != confirmPassword {
                        errorMessage = "Passwords do not match."
                        return
                    }
                    onConfirm(password)
                }
                .buttonStyle(PrimaryButtonStyle())
            }
        }
        .padding(20)
        .frame(width: 360)
    }
}

