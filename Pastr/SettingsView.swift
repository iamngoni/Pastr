// MARK: - Ignored App Row

struct IgnoredAppRow: View {
    let bundleId: String
    let onRemove: () -> Void

    private var appInfo: (name: String, icon: NSImage) {
        // Try to get app info from bundle ID
        if let appURL = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleId) {
            let appName = FileManager.default.displayName(atPath: appURL.path)
            let icon = NSWorkspace.shared.icon(forFile: appURL.path)
            return (appName, icon)
        }

        // Fallback for known system apps
        let knownApps: [String: String] = [
            "com.apple.keychainaccess": "Keychain Access",
            "com.apple.Passwords": "Passwords",
            "com.agilebits.onepassword7": "1Password 7",
            "com.1password.1password": "1Password",
            "com.lastpass.LastPass": "LastPass",
            "com.bitwarden.desktop": "Bitwarden",
        ]

        let name = knownApps[bundleId] ?? bundleId
        let fallbackIcon =
            NSImage(systemSymbolName: "app.fill", accessibilityDescription: nil) ?? NSImage()
        return (name, fallbackIcon)
    }

    var body: some View {
        HStack(spacing: 10) {
            Image(nsImage: appInfo.icon)
                .resizable()
                .frame(width: 24, height: 24)

            Text(appInfo.name)
                .font(.system(size: 13))
                .foregroundColor(Color(white: 0.85))

            Spacer()

            Button {
                onRemove()
            } label: {
                Image(systemName: "xmark")
                    .font(.system(size: 10, weight: .medium))
                    .foregroundColor(Color(white: 0.5))
            }
            .buttonStyle(.plain)
            .opacity(0.6)
        }
        .padding(.horizontal, 12)
        .padding(.vertical, 8)
    }
}

// MARK: - App Picker View

struct AppPickerView: View {
    @ObservedObject var settings: SettingsStore
    @Binding var isPresented: Bool
    @State private var searchText = ""
    @State private var installedApps: [AppInfo] = []

    struct AppInfo: Identifiable, Hashable {
        let id = UUID()
        let bundleId: String
        let name: String
        let icon: NSImage

        func hash(into hasher: inout Hasher) {
            hasher.combine(bundleId)
        }

        static func == (lhs: AppInfo, rhs: AppInfo) -> Bool {
            lhs.bundleId == rhs.bundleId
        }
    }

    var filteredApps: [AppInfo] {
        if searchText.isEmpty {
            return installedApps
        }
        return installedApps.filter {
            $0.name.localizedCaseInsensitiveContains(searchText)
                || $0.bundleId.localizedCaseInsensitiveContains(searchText)
        }
    }

    var body: some View {
        VStack(spacing: 0) {
            // Header
            HStack {
                Text("Add Ignored Application")
                    .font(.system(size: 15, weight: .semibold))
                    .foregroundColor(.white)
                Spacer()
                Button {
                    isPresented = false
                } label: {
                    Image(systemName: "xmark.circle.fill")
                        .font(.system(size: 18))
                        .foregroundColor(Color(white: 0.5))
                }
                .buttonStyle(.plain)
            }
            .padding(16)

            // Search field
            HStack {
                Image(systemName: "magnifyingglass")
                    .foregroundColor(Color(white: 0.5))
                TextField("Search applications...", text: $searchText)
                    .textFieldStyle(.plain)
                    .foregroundColor(.white)
            }
            .padding(10)
            .background(
                RoundedRectangle(cornerRadius: 8)
                    .fill(Color.white.opacity(0.08))
            )
            .padding(.horizontal, 16)

            // App list
            ScrollView {
                LazyVStack(spacing: 0) {
                    ForEach(filteredApps) { app in
                        let isIgnored = settings.ignoredAppBundleIds.contains(app.bundleId)

                        Button {
                            if isIgnored {
                                settings.removeIgnoredApp(app.bundleId)
                            } else {
                                settings.addIgnoredApp(app.bundleId)
                            }
                        } label: {
                            HStack(spacing: 12) {
                                Image(nsImage: app.icon)
                                    .resizable()
                                    .frame(width: 32, height: 32)

                                VStack(alignment: .leading, spacing: 2) {
                                    Text(app.name)
                                        .font(.system(size: 13))
                                        .foregroundColor(.white)

                                    Text(app.bundleId)
                                        .font(.system(size: 10))
                                        .foregroundColor(Color(white: 0.5))
                                }

                                Spacer()

                                if isIgnored {
                                    Image(systemName: "checkmark.circle.fill")
                                        .foregroundColor(Color(red: 0.04, green: 0.52, blue: 1))
                                }
                            }
                            .padding(.horizontal, 16)
                            .padding(.vertical, 10)
                            .background(Color.white.opacity(0.001))  // For hit testing
                        }
                        .buttonStyle(.plain)

                        Divider()
                            .background(Color.white.opacity(0.05))
                    }
                }
            }
            .frame(height: 300)

            // Done button
            HStack {
                Spacer()
                Button("Done") {
                    isPresented = false
                }
                .buttonStyle(PrimaryButtonStyle())
            }
            .padding(16)
        }
        .frame(width: 400)
        .background(Color(nsColor: NSColor(red: 0.11, green: 0.11, blue: 0.118, alpha: 1)))
        .onAppear {
            loadInstalledApps()
        }
    }

    private func loadInstalledApps() {
        DispatchQueue.global(qos: .userInitiated).async {
            var apps: [AppInfo] = []

            let appDirectories = [
                "/Applications",
                "/System/Applications",
                "/System/Applications/Utilities",
                NSHomeDirectory() + "/Applications",
            ]

            for directory in appDirectories {
                guard let contents = try? FileManager.default.contentsOfDirectory(atPath: directory)
                else { continue }

                for item in contents where item.hasSuffix(".app") {
                    let appPath = (directory as NSString).appendingPathComponent(item)
                    let bundlePath = (appPath as NSString).appendingPathComponent(
                        "Contents/Info.plist")

                    guard let plist = NSDictionary(contentsOfFile: bundlePath),
                        let bundleId = plist["CFBundleIdentifier"] as? String
                    else { continue }

                    let appName =
                        (plist["CFBundleDisplayName"] as? String)
                        ?? (plist["CFBundleName"] as? String)
                        ?? (item as NSString).deletingPathExtension

                    let icon = NSWorkspace.shared.icon(forFile: appPath)

                    apps.append(AppInfo(bundleId: bundleId, name: appName, icon: icon))
                }
            }

            // Sort alphabetically
            apps.sort { $0.name.localizedCaseInsensitiveCompare($1.name) == .orderedAscending }

            // Remove duplicates
            var seen = Set<String>()
            apps = apps.filter { seen.insert($0.bundleId).inserted }

            DispatchQueue.main.async {
                self.installedApps = apps
            }
        }
    }
}

